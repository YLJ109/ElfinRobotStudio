// Requires tools/start_ui_check.py. Never sends robot motion commands.
async (page) => {
  const failures = [], motion = [], results = []
  const onError = e => failures.push(e.message)
  const onRequest = r => { if (/\/api\/(estop|movej|jog|control|power|ready|program\/start)(\/|$)/.test(new URL(r.url()).pathname)) motion.push(r.url()) }
  const assert = (condition, label) => { if (!condition) throw new Error(label); results.push(label) }
  page.on('pageerror', onError); page.on('request', onRequest)
  try {
    await page.setViewportSize({ width: 1366, height: 768 })
    await page.goto('http://127.0.0.1:8711/#/work/program')
    await page.evaluate(() => { localStorage.setItem('huayan.side.width', '384'); localStorage.setItem('huayan.side.open', '1') })
    await page.reload()
    const editor = page.getByRole('textbox', { name: '程序代码', exact: true })
    await editor.waitFor()
    const panel = page.locator('.program-panel')
    await panel.getByRole('button', { name: '中文', exact: true }).click()
    await editor.fill('z')
    await page.locator('.cm-completionLabel').filter({ hasText: '直线移动' }).waitFor()
    assert((await page.locator('.cm-completionLabel').allTextContents()).every(s => !/^[A-Z_]+$/.test(s)), 'Chinese completion labels')
    const geometry = await page.evaluate(() => {
      const tooltip = document.querySelector('.program-completions'), r = tooltip.getBoundingClientRect()
      const range = document.createRange(); range.selectNodeContents(document.querySelector('.cm-line'))
      const text = range.getBoundingClientRect()
      return r.top >= text.bottom - 1 && tooltip.contains(document.elementFromPoint(r.left + 20, r.top + 10))
    })
    assert(geometry, 'Completion list below code and not obscured')
    await page.keyboard.press('Tab')
    assert((await editor.innerText()).trim() === '直线移动()', 'Tab inserts Chinese command')
    await panel.getByRole('button', { name: 'EN', exact: true }).click()
    await editor.fill('s')
    await page.locator('.cm-completionLabel').filter({ hasText: 'SPEED' }).waitFor()
    assert((await page.locator('.cm-completionLabel').allTextContents()).every(s => /^[A-Za-z_]+$/.test(s)), 'English completion labels')
    await page.keyboard.press('Enter')
    assert((await editor.innerText()).trim() === 'SPEED()', 'Enter inserts English command')
    await page.keyboard.press('Control+z')
    assert((await editor.innerText()).trim() === 's', 'Undo completion')
    await editor.fill('m')
    await page.locator('.cm-completionLabel').filter({ hasText: 'MOVEJ' }).waitFor()
    await page.keyboard.press('ArrowDown'); await page.keyboard.press('Tab')
    assert((await editor.innerText()).trim() === 'MOVEL()', 'Arrow navigation chooses second command')
    await editor.fill('s'); await page.locator('.program-completions').waitFor()
    await page.keyboard.press('Escape')
    assert(await page.locator('.program-completions').count() === 0, 'Escape dismisses completion')
    await panel.getByRole('button', { name: '中文', exact: true }).click()
    await editor.fill('直')
    await page.locator('.cm-completionLabel').filter({ hasText: '直线移动' }).waitFor()
    await page.keyboard.press('Tab')
    assert((await editor.innerText()).trim() === '直线移动()', 'Chinese prefix completion')
    await editor.fill('sXYZ 15'); await page.keyboard.press('Home'); await page.keyboard.press('ArrowRight'); await page.keyboard.press('Control+Space')
    await page.locator('.cm-completionLabel').filter({ hasText: '速度' }).waitFor(); await page.keyboard.press('Tab')
    assert((await editor.innerText()).trim() === '速度 15', 'Completion replaces whole token and preserves arguments')
    await editor.fill('工具 dk'); await page.locator('.cm-completionLabel').filter({ hasText: '打开' }).waitFor(); await page.keyboard.press('Tab')
    assert((await editor.innerText()).trim() === '工具 打开', 'Chinese tool action completion')
    await editor.fill('速度 15')
    await page.keyboard.press('Control+Space')
    assert(await page.locator('.program-completions').count() === 0, 'No command suggestions in numeric arguments')
    await editor.fill('# s'); await page.keyboard.press('Control+Space')
    assert(await page.locator('.program-completions').count() === 0, 'No suggestions inside comments')
    await editor.fill('速度 15\n等待 0.2')
    await panel.getByRole('button', { name: '解析', exact: true }).click()
    await page.getByText('解析成功 · 2 步', { exact: true }).waitFor()
    assert(await panel.getByRole('button', { name: '启动', exact: true }).isEnabled(), 'Valid program parses')
    await editor.fill('速度 20\n等待 0.2')
    assert(await panel.getByRole('button', { name: '启动', exact: true }).isDisabled(), 'Editing invalidates old parsed program')
    await page.getByRole('textbox', { name: '程序名称', exact: true }).fill('UI-test-draft')
    const railGeometry = await page.evaluate(() => {
      const button = document.querySelector('.rail-toggle').getBoundingClientRect(), rail = document.querySelector('.rail').getBoundingClientRect()
      return rail.bottom - button.bottom < 12
    })
    assert(railGeometry, 'Sidebar toggle at bottom')
    await page.getByRole('button', { name: '收起左侧栏', exact: true }).click()
    assert(!(await editor.isVisible()), 'Sidebar collapses')
    await page.getByRole('button', { name: '展开左侧栏', exact: true }).click()
    assert((await editor.innerText()).includes('速度 20') && await page.getByRole('textbox', { name: '程序名称' }).inputValue() === 'UI-test-draft', 'Sidebar retains code and unsaved draft')
    const sideBefore = await page.locator('.side').boundingBox(), handle = await page.locator('.side-resizer').boundingBox()
    await page.mouse.move(handle.x + handle.width / 2, handle.y + 100); await page.mouse.down()
    await page.mouse.move(handle.x + 70, handle.y + 100, { steps: 5 }); await page.mouse.up()
    await page.waitForFunction(previous => document.querySelector('.side').getBoundingClientRect().width > previous + 50, sideBefore.width)
    assert((await page.locator('.side').boundingBox()).width > sideBefore.width + 50, 'Sidebar width drags without obscuring editor')
    await panel.getByRole('button', { name: '保存', exact: true }).click()
    await page.getByText('已保存：UI-test-draft', { exact: true }).waitFor()
    assert(await page.getByRole('combobox', { name: '已保存程序' }).inputValue() === 'UI-test-draft', 'Program saves with selected name')
    for (const [width, height] of [[1920,1080], [1280,720], [1024,768], [768,768]]) {
      await page.setViewportSize({ width, height })
      await page.evaluate(() => new Promise(r => requestAnimationFrame(() => requestAnimationFrame(r))))
      const fits = await page.evaluate(() => {
        const r = document.querySelector('.program-panel').getBoundingClientRect()
        return [...document.querySelectorAll('.language-switch button, .library-save button, .library-load button')].every(el => {
          const b = el.getBoundingClientRect(); return b.left >= r.left && b.right <= r.right
        })
      })
      assert(fits, 'Editor controls fit ' + width)
      await panel.getByRole('button', { name: '载入', exact: true }).scrollIntoViewIfNeeded()
      const reachable = await panel.getByRole('button', { name: '载入', exact: true }).evaluate(el => {
        const r = el.getBoundingClientRect(); return el.contains(document.elementFromPoint(r.left + r.width / 2, r.top + r.height / 2))
      })
      assert(reachable, 'Library controls reachable ' + width)
    }
    await panel.getByRole('button', { name: '规则', exact: true }).click()
    await page.getByText('中英文编程规则', { exact: true }).waitFor()
    assert(page.url().endsWith('#/about'), 'Help opens centralized About guide')
    assert(failures.length === 0, 'No browser exceptions: ' + failures.join(', '))
    assert(motion.length === 0, 'No robot command sent')
    return { checks: results.length, results }
  } finally { page.off('pageerror', onError); page.off('request', onRequest) }
}
